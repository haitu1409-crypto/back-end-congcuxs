/**
 * Tìm tất cả các bộ số chứa số đã cho
 * @param {string} number - Số 2 chữ số (00-99)
 * @returns {string[]} - Mảng các setId (00-99) chứa số này
 */
function findSetsContainingNumber(number) {
    if (!number || typeof number !== 'string') {
        return [];
    }
    
    const numStr = number.padStart(2, '0');
    const containingSets = [];
    
    // Duyệt qua tất cả 100 bộ
    for (let i = 0; i < 100; i++) {
        const setId = String(i).padStart(2, '0');
        const setNumbers = SPECIAL_SETS.get(setId);
        
        if (setNumbers && setNumbers.includes(numStr)) {
            containingSets.push(setId);
        }
    }
    
    return containingSets;
}

